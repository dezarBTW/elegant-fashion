async (page) => {
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  const dismiss = page.getByRole('button', { name: 'Reject non-essential' });
  if (await dismiss.isVisible()) await dismiss.click();
  const name = (await page.getByRole('heading', { level: 3 }).first().innerText()).trim();
  const selector = page.getByRole('combobox', { name: `Quantity for ${name}`, exact: true });
  await selector.selectOption('5');
  const add = (quantity) => page.getByRole('button', { name: `Add ${quantity} of ${name} to cart`, exact: true });
  await add(5).hover();
  await add(5).click();
  const open = () => page.getByRole('button', { name: /^Open cart,/ }).click();
  const drawer = page.getByRole('dialog', { name: /Your cart/ });
  const increase = () => page.getByRole('button', { name: `Increase quantity of ${name}`, exact: true });
  const decrease = () => page.getByRole('button', { name: `Decrease quantity of ${name}`, exact: true });
  const expectQuantity = async (quantity) => {
    await drawer.getByText(`Quantity: ${quantity}`, { exact: true }).waitFor();
    check(await drawer.getByRole('article').count() === 1, 'Duplicate product rows in cart.');
    const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('elegant-style-cart')));
    check(saved.length === 1 && saved[0].quantity === quantity, 'Stored quantity does not match the cart.');
    return saved[0].id;
  };
  await open();
  await expectQuantity(5);
  await increase().click();
  await expectQuantity(6);
  await decrease().click();
  await expectQuantity(5);
  await page.getByRole('button', { name: 'Close cart', exact: true }).click();
  await selector.selectOption('1');
  await add(1).hover();
  await add(1).click();
  await add(1).click();
  await open();
  const id = await expectQuantity(7);
  for (let index = 0; index < 3; index++) await increase().click();
  await expectQuantity(10);
  check(await increase().isDisabled(), 'Maximum quantity is not enforced.');
  for (let index = 0; index < 5; index++) await decrease().click();
  await expectQuantity(5);
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.screenshot({ path: 'output/playwright/cart-quantity-desktop.png' });
  await page.setViewportSize({ width: 320, height: 740 });
  check(!await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), 'Mobile page overflows.');
  check(await drawer.evaluate((element) => element.scrollWidth <= element.clientWidth), 'Mobile drawer overflows.');
  await page.screenshot({ path: 'output/playwright/cart-quantity-mobile.png' });
  await page.evaluate((productId) => localStorage.setItem('elegant-style-cart', JSON.stringify([{ id: productId }, { id: productId }, { id: productId }])), id);
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.getByRole('button', { name: 'Open cart, 3 units', exact: true }).waitFor();
  await open();
  await expectQuantity(3);
  await increase().click();
  await increase().click();
  await expectQuantity(5);
  await page.getByRole('link', { name: 'Continue to checkout', exact: true }).click();
  await page.getByText(`${name} × 5`, { exact: true }).waitFor();
  check(await page.getByText(`${name} × 5`, { exact: true }).count() === 1, 'Checkout has duplicate product lines.');
  let submitted;
  await page.route('**/api/checkout', async (route) => {
    submitted = route.request().postDataJSON();
    await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Browser verification only; no payment created.', uncertain: true }) });
  });
  await page.getByRole('textbox', { name: 'Full name', exact: true }).fill('Quantity Test');
  await page.getByRole('textbox', { name: 'Email', exact: true }).fill('quantity@example.invalid');
  await page.getByRole('textbox', { name: 'Phone number', exact: true }).fill('08012345678');
  await page.getByRole('button', { name: /^Pay / }).click();
  await page.getByText('Browser verification only; no payment created.', { exact: true }).waitFor();
  check(submitted.items.length === 1 && submitted.items[0].productId === id && submitted.items[0].quantity === 5, 'Checkout request has incorrect quantities.');
  await page.screenshot({ path: 'output/playwright/checkout-quantity-mobile.png', fullPage: true });
  console.log(JSON.stringify({ quantitySelection: true, mergedRepeatedAdds: true, cartControls: true, maximumQuantity: true, legacyCartMigration: true, mobileLayout: true, checkoutSingleLine: true, checkoutRequestQuantity: 5, livePaymentsCreated: 0 }));
}
